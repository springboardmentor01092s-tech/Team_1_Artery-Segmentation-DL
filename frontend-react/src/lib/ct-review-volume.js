import {decode} from './nifti-decode.js';
import {inspectVolume,sameAffine,volumeBudget,MAX_TRANSFER_BYTES} from './volume-geometry.js';

export async function verifyOriginalCt(buffer,source){
  if(!source||!Number.isSafeInteger(source.case_id)||source.case_id<1||source.units!=='mm'
    ||typeof source.source_sha256!=='string'||!/^[a-f0-9]{64}$/.test(source.source_sha256))throw new Error('The assigned CT has no verifiable source identity.');
  const {voxels}=volumeBudget(source.shape);
  if(!(buffer instanceof ArrayBuffer)||!buffer.byteLength||buffer.byteLength>MAX_TRANSFER_BYTES)throw new Error('CT input exceeds the browser transfer limit.');
  const hash=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',buffer)),v=>v.toString(16).padStart(2,'0')).join('');
  if(hash!==source.source_sha256)throw new Error('Original CT checksum mismatch. No image was displayed.');
  const ct=decode(buffer,Math.min(MAX_TRANSFER_BYTES,voxels*8+1024*1024));
  const geometry=inspectVolume(ct);
  if(geometry.shape.some((n,i)=>n!==source.shape[i])||!sameAffine(geometry.affine,source.affine))
    throw new Error('Original CT geometry does not match the assignment. No image was displayed.');
  return {ct,geometry};
}

// Display-only coordinates for the already verified orthogonal/permuted grid.
// No lesion location or measurement is generated by moving the crosshair.
export function ctReviewNativePoint(world,geometry){
  if(!Array.isArray(world)||world.length!==3||!world.every(Number.isFinite))return null;
  const point=[];
  for(let col=0;col<3;col++){
    const axis=geometry.affine.slice(0,3).findIndex(row=>Math.abs(row[col])>1e-5);
    if(axis<0)return null;
    const value=(world[axis]-geometry.affine[axis][3])/geometry.affine[axis][col];
    if(!Number.isFinite(value)||value< -1e-4||value>geometry.shape[col]-1+1e-4)return null;
    point.push(Number(Math.min(geometry.shape[col]-1,Math.max(0,value)).toFixed(5)));
  }
  return point;
}
