import { test, expect } from '@playwright/test';
import { installApi } from './fixtures';
import { EXPERIMENT_NOTICE } from '../../src/lib/experimental-candidates';
import { loadExperimentalFixture } from '../experimental-candidates-fixtures';

for (const permuted of [false, true]) test(`isolated experimental preview source binding and actual CT marker projection (${permuted ? 'permuted' : 'flipped'})`, async ({ page }) => {
  const errors = [], writes = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.method() !== 'GET') writes.push(request.url()); });
  await installApi(page, {role:'Researcher'});
  const layout=permuted?'permuted':'flipped';
  const {preview,geometry,segmentation:parent,ctGzip:ct,maskGzip:mask}=await loadExperimentalFixture(layout);
  await page.route('**/api/v1/cases/1/segmentations**', route => {
    const path = new URL(route.request().url()).pathname;
    return path.endsWith('/segmentations') ? route.fulfill({json:[parent]}) : route.fulfill({contentType:'application/gzip',body:path.endsWith('/source')?ct:mask});
  });
  const world = ijk => geometry.affine.slice(0,3).map(row=>row[3]+row.slice(0,3).reduce((s,n,i)=>s+n*ijk[i],0));
  expect(preview.candidates[0].sample_ijk).toEqual([16,16,34]);
  await page.goto('/cases/1/analysis');
  await page.getByRole('button',{name:`View CT + Segmentation for run ${parent.id}`}).click();
  await expect(page.getByText(/Voxel spacing \(original axes\):/)).toBeVisible({timeout:30000});
  await page.getByText('Experimental local candidate preview',{exact:true}).click();
  const input = page.getByLabel('Local experimental candidate JSON',{exact:true});
  const upload = data => input.setInputFiles({name:'synthetic-preview.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
  await upload(preview);
  await expect(page.getByText('Supplied algorithm: experimental-mask-profile / 0.1.0.',{exact:false})).toBeVisible();
  await expect(page.getByText(EXPERIMENT_NOTICE,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Locate experimental candidate-001 (main)',exact:true}).click();
  const ras = world([16,16,34]).map(n=>n.toFixed(2)).join(', ');
  await expect(page.getByText(`Crosshair RAS: ${ras} mm`,{exact:false})).toBeVisible();
  const marker = page.getByRole('button',{name:'Locate Axial experimental candidate-001',exact:true});
  await expect(marker).toBeVisible();
  await expect(marker).toHaveCSS('background-color','rgb(245, 158, 11)');
  const portal=page.locator('[aria-label="Experimental candidate locations"]');
  await expect(portal).toHaveCount(1);
  expect(await portal.evaluate(node=>node.closest('details.no-print')===null)).toBe(true);
  await expect(portal).toHaveClass(/no-print/);
  await page.emulateMedia({media:'print'});
  await expect(portal).toBeHidden();
  await expect(page.getByText(EXPERIMENT_NOTICE,{exact:true})).toBeHidden();
  await expect(page.locator('.volume-canvas-container canvas')).toBeVisible();
  await expect(page.getByRole('heading',{name:'CT + predicted segmentation',exact:true})).toBeVisible();
  await page.emulateMedia({media:'screen'});
  await expect(portal).toBeVisible();
  await expect(marker).toBeVisible();
  await expect(page.getByText(EXPERIMENT_NOTICE,{exact:true})).toBeVisible();
  await page.getByText('Experimental local candidate preview',{exact:true}).click();
  await expect(marker).toHaveCount(0);
  await page.getByText('Experimental local candidate preview',{exact:true}).click();
  await expect(marker).toBeVisible();
  await page.screenshot({path:test.info().outputPath('synthetic-experimental-preview.png'),fullPage:true});
  await marker.click();
  const wrong = structuredClone(preview);wrong.source.mask_sha256='d'.repeat(64);
  await upload(wrong);
  await expect(page.getByRole('alert')).toContainText('Preview source/mask identity mismatch');
  await expect(marker).toHaveCount(0);
  const reference = structuredClone(preview);reference.source.mask_role='reference_annotation';
  await upload(reference);
  await expect(page.getByRole('alert')).toContainText('annotations are not predictions');
  await upload((await loadExperimentalFixture(layout,'no_candidate_preview')).preview);
  await expect(page.getByText('Preview state: no_candidates_in_evaluable_sections.',{exact:false})).toBeVisible();
  await expect(marker).toHaveCount(0);
  const unavailable = (await loadExperimentalFixture(layout,'abstained_preview')).preview;
  await upload(unavailable);
  await expect(page.getByText('Preview state: abstained.',{exact:false})).toBeVisible();
  await expect(page.getByRole('button',{name:/Locate .*experimental candidate/})).toHaveCount(0);
  expect(errors).toEqual([]);expect(writes).toEqual([]);
});
